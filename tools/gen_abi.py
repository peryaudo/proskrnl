#!/usr/bin/env python3
"""gen_abi.py - generate abi/ headers from Wine's headers (Constitution Art. 4).

Every numeric value in abi/ (NTSTATUS codes, contract enums, boundary limits)
is extracted from third_party/wine/include/*.h - never typed by hand and never
recalled from model memory. Re-run after bumping the Wine submodule:

    python3 tools/gen_abi.py            # writes abi/ntstatus.h, abi/ntdef.h

The non-numeric scaffold (base typedefs, LIST_ENTRY/LARGE_INTEGER shapes) is
fixed text below; it carries static_asserts so a drift fails at compile time.
"""

import argparse
import re
import sys
from pathlib import Path

BANNER = """\
/* {name} - GENERATED by tools/gen_abi.py from {source}.
 * DO NOT EDIT BY HAND (Constitution Art. 4 / gate G4). Regenerate with:
 *     python3 tools/gen_abi.py
 */
"""


def gen_ntstatus(wine: Path) -> str:
    """Extract every `#define STATUS_* ((NTSTATUS) 0x...)` from Wine's ntstatus.h."""
    src = (wine / "include/ntstatus.h").read_text()
    pattern = re.compile(
        r"^#define\s+(STATUS_\w+)\s+\(\(NTSTATUS\)\s*(0x[0-9A-Fa-f]+)\)", re.M
    )
    lines = [
        f"#define {name} ((NTSTATUS) {value})" for name, value in pattern.findall(src)
    ]
    if len(lines) < 2000:
        sys.exit(f"gen_abi: ntstatus extraction looks wrong ({len(lines)} values)")
    body = "\n".join(lines)
    return (
        BANNER.format(name="abi/ntstatus.h", source="wine/include/ntstatus.h")
        + "#ifndef PROSKRNL_ABI_NTSTATUS_H\n"
        + "#define PROSKRNL_ABI_NTSTATUS_H\n\n"
        + '#include "abi/ntdef.h"\n\n'
        + body
        + "\n\n#endif /* PROSKRNL_ABI_NTSTATUS_H */\n"
    )


def extract_defines(src: str, source_name: str, names: list[str]) -> str:
    """Pull `#define NAME value` lines verbatim, in the order given (so a
    definition may reference an earlier one). Backslash-continued definitions
    (e.g. winnt.h's FILE_GENERIC_READ) are joined; function-like macros
    (e.g. winnt.h's LANGIDFROMLCID) keep their parameter list. Values are
    never retyped."""
    lines = []
    for name in names:
        match = re.search(
            r"^#define\s+"
            + re.escape(name)
            + r"(\([^)\n]*\))?\s+((?:[^\n]*\\\n)*[^\n]*?)\s*$",
            src,
            re.M,
        )
        if not match:
            sys.exit(f"gen_abi: #define {name} not found in {source_name}")
        params = match.group(1) or ""
        value = re.sub(r"\s*\\\n\s*", " ", match.group(2))
        lines.append(f"#define {name}{params} {value}")
    return "\n".join(lines)


def extract_struct(src: str, tag: str, typedef: str, keep_tag: bool = False) -> str:
    """Pull one `typedef struct _TAG { ... } NAME, *PNAME...;` body verbatim.
    The reserved `_TAG` tag is dropped by default; members are kept
    byte-for-byte. keep_tag preserves the tag so another header can carry a
    forward declaration (`typedef struct _TAG NAME;`) of the same type."""
    # An empty tag means the header declares it ANONYMOUSLY
    # (`typedef struct { ... } NAME, *PNAME;`), which winnt.h does for the
    # power structures among others. Without this the search fails and the
    # generator exits — loudly, but with a message containing no "error",
    # which is easy to miss while stale abi/ headers keep the build green
    # (docs/21).
    match = re.search(
        r"typedef struct " + (tag + r"\s*" if tag else "") +
        # With no tag the body must not cross a brace, or the lazy match
        # walks from the FIRST anonymous struct in the header to the
        # target's closing brace and swallows every struct in between.
        r"\{(" + (r".*?" if tag else r"[^{}]*?") + r")\}\s*([^;{}]*" + typedef + r"[^;{}]*)\s*;",
        src,
        re.S,
    )
    if not match:
        sys.exit(f"gen_abi: struct {typedef} not found")
    intro = "typedef struct " + (tag + " " if keep_tag else "") + "{"
    return intro + match.group(1) + "} " + match.group(2).strip() + ";"


def extract_union(src: str, tag: str, typedef: str) -> str:
    """Pull one `typedef union _TAG { ... } NAME, *PNAME...;` body verbatim
    (the winnt.h FILE_SEGMENT_ELEMENT shape). Same contract as
    extract_struct: the reserved `_TAG` tag is dropped, members are kept
    byte-for-byte."""
    match = re.search(
        r"typedef union " + tag + r"\s*\{(.*?)\}\s*([^;{}]*" + typedef + r"[^;{}]*)\s*;",
        src,
        re.S,
    )
    if not match:
        sys.exit(f"gen_abi: union {typedef} not found")
    return "typedef union {" + match.group(1) + "} " + match.group(2).strip() + ";"


def extract_plain_struct(src: str, name: str) -> str:
    """Pull one `struct NAME { ... };` body verbatim (the wine/condrv.h shape:
    plain struct tags, no typedef)."""
    match = re.search(r"struct " + re.escape(name) + r"\s*\{(.*?)\}\s*;", src, re.S)
    if not match:
        sys.exit(f"gen_abi: struct {name} not found")
    return "struct " + name + "\n{" + match.group(1) + "};"


def extract_anonymous_struct(src: str, typedef: str) -> str:
    """Pull one tagless `typedef struct { ... } NAME;` body verbatim (the
    wine/condrv.h char_info_t shape). The body match excludes braces so the
    search can't start at an earlier unrelated `typedef struct {` and swallow
    everything up to NAME (flat structs only)."""
    match = re.search(
        r"typedef struct\s*\{([^{}]*?)\}\s*(" + re.escape(typedef) + r")\s*;", src, re.S
    )
    if not match:
        sys.exit(f"gen_abi: anonymous struct {typedef} not found")
    return "typedef struct\n{" + match.group(1) + "} " + match.group(2) + ";"


def extract_plain_enum(src: str, name: str) -> str:
    """Pull one `enum NAME { ... };` body verbatim (values are positional, so
    the body must come from the Wine header, not from memory)."""
    match = re.search(r"enum " + re.escape(name) + r"\s*\{(.*?)\}\s*;", src, re.S)
    if not match:
        sys.exit(f"gen_abi: enum {name} not found")
    return "enum " + name + "\n{" + match.group(1) + "};"


def extract_anonymous_enum(src: str, typedef: str) -> str:
    """Pull one tagless `typedef enum { ... } NAME;` body verbatim (the
    winternl.h VIRTUAL_MEMORY_INFORMATION_CLASS shape). Anchored on the
    typedef name so the search cannot start at an earlier unrelated
    tagless enum (values are positional — never retyped)."""
    match = re.search(
        r"typedef enum\s*\{([^{}]*?)\}\s*(" + re.escape(typedef) + r"[^;{}]*)\s*;",
        src,
        re.S,
    )
    if not match:
        sys.exit(f"gen_abi: anonymous enum {typedef} not found")
    return "typedef enum\n{" + match.group(1) + "} " + match.group(2).strip() + ";"


def extract_prototypes(src: str, names: list[str]) -> str:
    """Pull `NTSYSAPI <ret> WINAPI Nt*(...)` prototypes verbatim from Wine's
    winternl.h, dropping the Windows linkage macros (signatures are contract;
    calling convention on x86_64 kernel builds is the platform default)."""
    lines = []
    for name in names:
        match = re.search(
            r"^NTSYSAPI\s+([\w* ]+?)\s+(?:WINAPI|NTAPI)\s+" + name + r"\s*\((.*)\);\s*$",
            src,
            re.M,
        )
        if not match:
            sys.exit(f"gen_abi: prototype {name} not found in winternl.h")
        ret, args = match.group(1).strip(), match.group(2).strip()
        lines.append(f"{ret} {name}({args});")
    return "\n".join(lines)


def resolve_ifdef(text: str, macro: str, keep: bool) -> str:
    """Resolve `#ifdef MACRO` / `#else` / `#endif` blocks in an extracted
    struct body, keeping the branch selected by `keep`. Only used for
    macros whose value is fixed by the project (e.g. __WINESRC__ selects
    the real NT field names in PROCESS_BASIC_INFORMATION); the member
    text itself stays byte-for-byte."""
    out = []
    stack = []  # each entry: (was_matching_macro, keeping_before, in_else)
    keeping = True
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("#ifdef"):
            name = stripped.split()[1] if len(stripped.split()) > 1 else ""
            if name == macro:
                stack.append((True, keeping, False))
                keeping = keeping and keep
                continue
            stack.append((False, keeping, False))
        elif stripped.startswith("#else") and stack and stack[-1][0]:
            matched, before, _ = stack[-1]
            stack[-1] = (matched, before, True)
            keeping = before and not keep
            continue
        elif stripped.startswith("#endif") and stack:
            matched, before, _ = stack.pop()
            if matched:
                keeping = before
                continue
            keeping = before
        if keeping:
            out.append(line)
    return "\n".join(out)


# Offset-comment forms in Wine's headers: `/* 32bit/64bit */` (winternl.h
# PEB/TEB), `/* 0x000 */` (wdm.h KUSER_SHARED_DATA), `/* 000 */` (winnt.h
# AMD64_CONTEXT). Trailing prose after the offsets is allowed.
OFFSET_COMMENT = re.compile(
    r"/\*\s*(?:0x)?([0-9a-fA-F]*)\s*(?:(/)\s*(?:0x)?([0-9a-fA-F]*))?"
    r"(?:\s[^*]*)?\*/"
)
MEMBER_DECL = re.compile(r"([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*;")


def gen_offset_asserts(struct_text: str, typedef: str) -> str:
    """Turn Wine's own per-member offset comments into _Static_asserts, so
    every extracted layout is pinned against the exact source it came from
    (Art. 4: the numbers are read from the Wine header, never retyped).
    Only top-level, non-bitfield members with an x64 offset are pinned."""
    lines = []
    depth = 0
    body = struct_text[struct_text.index("{") + 1 : struct_text.rindex("}")]
    for line in body.splitlines():
        at_top = depth == 0
        depth += line.count("{") - line.count("}")
        if not at_top or depth != 0:
            continue  # inside (or entering/leaving) a nested union/struct
        comment = OFFSET_COMMENT.search(line)
        if not comment:
            continue
        offset = comment.group(3) if comment.group(2) else comment.group(1)
        if not offset:
            continue  # 32-bit-only column
        decl = line[: comment.start()]
        if ":" in decl:
            continue  # bitfield: no offsetof
        member = MEMBER_DECL.search(decl)
        if not member:
            continue
        lines.append(
            f"_Static_assert(offsetof({typedef}, {member.group(1)}) == 0x{offset.lower()}, "
            f'"{typedef} x64 layout (offset comment in the Wine header)");'
        )
    if not lines:
        sys.exit(f"gen_abi: no offset comments found for {typedef}")
    return "\n".join(lines)


def extract_enum(src: str, tag: str, typedef: str) -> str:
    """Pull one `typedef enum _TAG { ... } NAME;` block verbatim (values are
    positional, so the body must come from the Wine header, not from memory).
    The reserved `_TAG` struct tag is dropped; the body is kept byte-for-byte."""
    match = re.search(
        r"typedef enum " + tag + r"\s*\{(.*?)\}\s*([^;{}]*" + typedef + r"[^;{}]*)\s*;",
        src,
        re.S,
    )
    if not match:
        sys.exit(f"gen_abi: enum {typedef} not found")
    return "typedef enum {" + match.group(1) + "} " + match.group(2).strip() + ";"


