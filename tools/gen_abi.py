def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    root = Path(__file__).resolve().parent.parent
    parser.add_argument("--wine", type=Path, default=root / "third_party/wine")
    parser.add_argument("--out", type=Path, default=root / "abi")
    args = parser.parse_args()

    args.out.mkdir(exist_ok=True)
    for name, text in [
        ("ntdef.h", gen_ntdef(args.wine)),
        ("ntstatus.h", gen_ntstatus(args.wine)),
        ("ntobapi.h", gen_ntobapi(args.wine)),
        ("ntmmapi.h", gen_ntmmapi(args.wine)),
        ("ntimage.h", gen_ntimage(args.wine)),
        ("ntioapi.h", gen_ntioapi(args.wine)),
        ("ntcondrv.h", gen_ntcondrv(args.wine)),
        ("ntmountmgr.h", gen_ntmountmgr(args.wine)),
        ("ntcontext.h", gen_ntcontext(args.wine)),
        ("ntpsapi.h", gen_ntpsapi(args.wine)),
        ("ntpebteb.h", gen_ntpebteb(args.wine)),
        ("ntwow64.h", gen_ntwow64(args.wine)),
        ("ntkeapi.h", gen_ntkeapi(args.wine)),
        ("ntregapi.h", gen_ntregapi(args.wine)),
        ("ntseapi.h", gen_ntseapi(args.wine)),
    ]:
        (args.out / name).write_text(text)
        print(f"gen_abi: wrote abi/{name}")


if __name__ == "__main__":
    main()
